#!/usr/bin/env bash
# One-command LOCAL (development/test) database setup: roles, migrations, grants, demo data.
#   ./database/setup-dev.sh "postgresql://postgres:postgres@localhost:5432/smart_hospital?schema=public" [--no-seed]
# The URL is the PostgreSQL ADMIN login (used here only; never put it in backend/.env). The database must already exist (createdb).
# Roles are cluster-wide: set MEDICORE_MIGRATOR_PW / MEDICORE_APP_PW / MEDICORE_SEEDER_PW to keep passwords you already use for other
# MediCore databases on this server; otherwise new random ones are generated (and replace the old ones).
# NEVER run this against a production database (it creates the seeder role and loads demo data).
set -euo pipefail
ADMIN="${1:?usage: setup-dev.sh <admin database url> [--no-seed]}"
HERE="$(cd "$(dirname "$0")" && pwd)"; BACKEND="$HERE/../backend"
case "$ADMIN" in *prod*|*medicore\?*) echo "Refusing: this looks like a production database name." >&2; exit 1;; esac
gen() { openssl rand -base64 24 | tr -d '/+=\n'; }
MPW="${MEDICORE_MIGRATOR_PW:-$(gen)}"; APW="${MEDICORE_APP_PW:-$(gen)}"; SPW="${MEDICORE_SEEDER_PW:-$(gen)}"
as() { printf '%s' "$ADMIN" | sed -E "s#^([a-z]+://)[^@]*@#\1$1:$2@#"; }   # same host/database, different login
MIG="$(as medicore_migrator "$MPW")"; APP="$(as medicore_app "$APW")"; SEED="$(as medicore_seeder "$SPW")"
roles() { psql "${ADMIN%%\?*}" -q -v ON_ERROR_STOP=1 -v env=development -v with_seeder=on -v migrator_pw="$MPW" -v app_pw="$APW" -v seeder_pw="$SPW" -f "$HERE/roles.sql"; }
echo "1/4 roles and ownership";   roles
echo "2/4 migrations (as medicore_migrator)"; (cd "$BACKEND" && DATABASE_URL="$MIG" npx prisma migrate deploy)
echo "3/4 grants for the new tables"; roles
if [ "${2:-}" != "--no-seed" ]; then echo "4/4 demo data (as medicore_seeder)"; (cd "$BACKEND" && DATABASE_URL="$APP" SEED_DATABASE_URL="$SEED" node prisma/seed.js); fi
OUT="$BACKEND/.env.roles"; umask 077
{ echo "# generated by database/setup-dev.sh — copy DATABASE_URL into backend/.env (the API runs as the app role); keep the others private"
  echo "DATABASE_URL=\"$APP\""; echo "MIGRATION_DATABASE_URL=\"$MIG\""; echo "SEED_DATABASE_URL=\"$SEED\""; } > "$OUT"
echo "Done. Credentials written to backend/.env.roles (mode 600, git-ignored). Use:  DATABASE_URL=<MIGRATION_DATABASE_URL> npm run db:deploy ; npm run db:seed with SEED_DATABASE_URL set."
