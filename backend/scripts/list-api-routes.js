// Lists every API route with who may call it and what is validated. Output is docs/api-routes.md (the starting point for an
// OpenAPI document). Run: node scripts/list-api-routes.js --write   (prints to stdout without --write)
// tests/api-contract.test.js fails when the file is out of date, so a new endpoint cannot be added without updating it.
require('dotenv').config({ quiet: true });
const fs = require('fs');
const path = require('path');

/** The text of an Express 4 mount path from the layer's regexp */
const mountPath = (layer) => {
  const m = layer.regexp.source.replace('\\/?(?=\\/|$)', '').replace(/^\^/, '').replace(/\\\//g, '/');
  return m === '' || m === '(?:/(?=$))?' ? '' : m.replace(/\(\?:\(\[\^\/\]\+\?\)\)/g, ':param');
};

function walk(stack, prefix, inherited, out) {
  let roles = inherited.roles; let login = inherited.login;
  for (const layer of stack) {
    if (layer.route) {
      const route = layer.route;
      let r = roles; let l = login; const validates = new Set(); const schemas = {};
      for (const h of route.stack) { if (h.handle.roles) r = h.handle.roles; if (h.handle.requiresLogin) l = true; (h.handle.validates || []).forEach((v) => validates.add(v)); Object.assign(schemas, h.handle.schemas || {}); }
      for (const method of Object.keys(route.methods)) out.push({ method: method.toUpperCase(), path: (prefix + route.path).replace(/\/+$/, '') || '/', roles: r, login: l, validates: [...validates], schemas });
    } else if (layer.name === 'router' && layer.handle.stack) {
      walk(layer.handle.stack, prefix + mountPath(layer), { roles, login }, out);
    } else if (layer.handle && layer.handle.roles) roles = layer.handle.roles;
    else if (layer.handle && layer.handle.requiresLogin) login = true;
  }
}

function inventory() {
  const app = require('../src/app');
  const out = [];
  walk(app._router.stack, '', { roles: null, login: false }, out);
  return out.filter((r) => r.path.startsWith('/api')).sort((a, b) => (a.path + a.method).localeCompare(b.path + b.method));
}

const DOWNLOADS = {
  'GET /api/files/reports/:id': 'file download (the uploaded file; JSON error envelope on failure)',
  'GET /api/files/prescriptions/:id/pdf': 'PDF',
  'GET /api/admin/reports/:type': 'JSON, or CSV with ?format=csv',
};
const access = (r) => (!r.login ? 'public' : r.roles ? r.roles.join(', ') : 'any signed-in user');
const REASON = new Set(['GET /api/admin/patients/:id', 'GET /api/admin/emergencies/:id', 'POST /api/admin/restore/:kind/:id', 'GET /api/admin/reports/:type', 'GET /api/files/reports/:id', 'GET /api/files/prescriptions/:id/pdf']);
const needsReason = (r) => REASON.has(`${r.method} ${r.path}`);

function markdown(routes) {
  const lines = [
    '# API route inventory', '',
    '_Generated by `node backend/scripts/list-api-routes.js --write` — do not edit by hand; `tests/api-contract.test.js` checks it is current._', '',
    `${routes.length} routes. All JSON responses follow [api-contract.md](api-contract.md). "Validated" lists which of params / query / body are checked with a schema.`, '',
    '| Method | Path | Access | Validated | Notes |', '|---|---|---|---|---|',
  ];
  for (const r of routes) {
    const notes = [DOWNLOADS[`${r.method} ${r.path}`], needsReason(r) ? 'administrators must send `X-Access-Reason` for clinical detail, downloads and patient-identifying reports' : null].filter(Boolean).join('; ');
    lines.push(`| ${r.method} | \`${r.path}\` | ${access(r)} | ${r.validates.join(', ') || '—'} | ${notes} |`);
  }
  return `${lines.join('\n')}\n`;
}

module.exports = { inventory, markdown };

if (require.main === module) {
  const md = markdown(inventory());
  if (process.argv.includes('--write')) { fs.writeFileSync(path.join(__dirname, '../../docs/api-routes.md'), md); console.log('written docs/api-routes.md'); } else console.log(md);
  process.exit(0);
}
